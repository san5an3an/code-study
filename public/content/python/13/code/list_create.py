# 리스트 만들기: 대괄호 안에 값을 쉼표로 나눠 적음 (강의 13강-리스트.ipynb 리스트 자료형 생성하기 정리)

# 5명의 학생에 대한 성적 나열 => 정수형 원소만 갖는 리스트예요
grade = [98, 82, 73, 64, 100]
print(grade)

# 각 학생의 이름 나열 => 문자열 원소만 갖는 리스트예요
names = ["철수", "영희", "나영", "민식", "호영"]
print(names)

# 서로 다른 자료형도 한 리스트에 같이 담을 수 있어요
stud1 = ["철수", 98]
stud2 = ["영희", 82]
stud3 = ["나영", 73]
print(stud1)
print(stud2)
print(stud3)

# 정수, 실수, 논리값, 문자열을 한꺼번에 담아도 돼요 (학습정리 슬라이드 예)
mixed = [1, 1.5, True, "a"]
print(mixed)
