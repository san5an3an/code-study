# 2차원 리스트 만들기: 리스트의 각 칸에 또 리스트를 넣음 (강의 슬라이드 2차원 리스트의 정의, 13강-리스트.ipynb 2차원 리스트의 생성 정리)

# 따로 만든 1차원 리스트들을 새 리스트의 원소로 넣어요
stud1 = ["철수", 98]
stud2 = ["영희", 82]
stud3 = ["나영", 73]
student_group = [stud1, stud2, stud3]
print(student_group)

# 처음부터 한 번에(일괄) 만들 수도 있어요
my_list = [[1, 2, 3], [10, 20, 30], [100, 200, 300]]
print(my_list)

# 보기 좋게 줄을 바꿔 써도 같은 리스트예요. 대괄호 안에서는 줄바꿈과 띄어쓰기가 자유로워요
student_group2 = [
    ["민식", 64, 172.3],
    ["호영", 100, 175.8],
    ["철민", 89, 168.7]
]
print(student_group2)   # 출력은 여전히 한 줄로 나와요

# 줄마다 칸 수가 달라도 돼요
uneven = [[1, 2, 3], [10, 20], [100]]
print(uneven)
