# 문자열 슬라이싱: [시작위치:끝위치] 로 구간을 잘라 냄, 끝위치 글자는 안 들어감 (강의 슬라이드 문자열의 슬라이싱 (1)~(3) 정리)

msg = "You need Python"

# 양의 정수로 need 꺼내기: 인덱스 4부터 8 전까지(8은 안 들어가요)
print(msg[4:8])

# 음의 정수로 need 꺼내기: -11부터 -7 전까지
print(msg[-11:-7])

# 양수와 음수를 섞어도 돼요: 4부터 -7 전까지
print(msg[4:-7])

# 시작위치만 쓰면 거기부터 끝까지 가져와요
print(msg[4:])
print(msg[-11:])

# 끝위치만 쓰면 처음부터 끝위치 전까지 가져와요
print(msg[:8])
print(msg[:-7])

# 둘 다 안 쓰고 콜론만 쓰면 처음부터 끝까지, 즉 전체예요
print(msg[:])

# 시작위치가 끝위치보다 오른쪽이면 에러는 안 나고 빈 문자열이 나와요
print(repr(msg[-8:-10]))   # ''
