# 프로젝트 예시 답안: 8자리 생년월일에서 연도를 잘라 세는 나이 구하기 (강의 슬라이드 생년월일로 나이 구하기 정리)

# 원래 과제는 input() 으로 받지만, 실행할 때마다 결과가 같도록 값을 직접 넣었어요
# 과제대로 하려면 birthday = input("생년월일(yyyymmdd): ") 로 바꾸면 돼요
birthday = "19930523"

# 앞 네 글자(인덱스 0부터 4 전까지)가 태어난 연도예요. 문자열이니까 int() 로 정수로 바꿔요
birth_year = int(birthday[0:4])

# 올해 연도예요. 실행하는 해에 맞게 직접 고쳐 써요
this_year = 2026

# 세는 나이는 태어날 때 1살이고 새해마다 1살씩 늘어요 => 올해 - 태어난 해 + 1
age = this_year - birth_year + 1
print("태어난 해:", birth_year)
print("세는 나이:", age)

# 월과 일도 같은 방법으로 잘라 낼 수 있어요
print("월:", birthday[4:6], "일:", birthday[6:])
