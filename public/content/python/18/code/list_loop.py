# 리스트를 for문으로 탐색하는 두 가지 방법 (강의 18강-반복문(2)-for.ipynb 리스트의 인덱스 자체로 반복의 범위를 지정하기, 리스트에 대한 반복 정리)

# 방법 1: 원소의 수를 구한 다음 그 길이로 반복 범위를 정해요
# -> 단점: 원소가 바로 담기는 변수가 없어서 seasons[i] 처럼 리스트를 통해 꺼내야 해요
seasons = ['봄', '여름', '가을', '겨울']

size = len(seasons)          # 길이는 4, 인덱스는 0~3이에요
for i in range(0, size):     # i가 0부터 4 전(=3)까지 1씩 증가해요
    print("%d번째 원소: %s" % (i, seasons[i]))

# 방법 2: 리스트 자체를 반복에 걸어요
# -> 리스트의 원소가 차례로 i에 담기면서 반복돼요
# -> 단점: 지금 원소가 몇 번째인지는 알 수 없어요
msg = ['python', 'is', 'good']

for i in msg:
    print(i)
