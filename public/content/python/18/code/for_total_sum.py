# 1~10까지의 총합 구하기 (강의 18강-반복문(2)-for.ipynb 총 합 구하기 정리)

# 총합을 누적해서 저장할 변수는 반복이 시작되기 전에 0으로 만들어 둬요
# 강의 화면에서는 변수 이름을 sum 으로 썼지만, sum 은 파이썬 내장 함수 이름이라 total 로 바꿨어요
total = 0

for x in range(1, 11):    # x가 1부터 11 전까지 1씩 증가하면서 반복해요
    # total 이 x만큼 스스로 증가해요
    # -> x가 1~10까지 변하니까 결국 1부터 10까지 차례로 더해져요
    total += x
    print("x=%d, sum=%d" % (x, total))
