# for문 기본 특성과 구구단 7단 (강의 18강-반복문(2)-for.ipynb for의 기본 특성, 구구단 7단 출력하기 정리)

# 초기식, 조건식, 증감식을 한 줄에 다 적어요
# x가 1부터 11 전까지(=10까지) 1씩 증가하면서 반복해요
for x in range(1, 11):
    # 반복이 진행되는 동안 수행할 명령이에요
    print("x=%d" % x)

# 구구단 7단: 가운데 숫자 y가 1부터 10 전까지(=9까지) 1씩 증가해요
for y in range(1, 10):
    z = 7 * y
    print("7 x %d = %d" % (y, z))
