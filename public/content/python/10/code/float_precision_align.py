# 실수의 소수점 자릿수와 정렬 %f, %0.3f, %10.3f, %-10.3f, %010.3f (강의 10강-형식문자를_활용한_문자열_포메팅.ipynb 소수점 표현하기, 실수의 정렬 정리)

# 실수값 표현하기. %f 는 소수점 아래 6자리까지 보여 줘요
money = 123.456789
print("[%f]원 입니다." % money)

# 소수점 3자리까지 표현하기 -> 소수점 4째자리에서 반올림돼요
print("[%0.3f]원 입니다." % money)

# 앞의 0을 빼고 %.3f 로 써도 결과가 같아요
print("[%.3f]원 입니다." % money)

# 소수점 3자리까지 표현하되 전체 글자수는 10글자 (빈자리 공백)
# 소수점도 자리수에 포함돼요
print("[%10.3f]원 입니다." % money)    # 오른쪽 정렬
print("[%-10.3f]원 입니다." % money)   # 왼쪽 정렬

# 소수점 3자리까지 표현하되 전체 글자수는 10글자 (빈자리 0)
# 빈 자리를 0으로 채우는 경우는 오른쪽 정렬만 가능해요
print("[%010.3f]원 입니다." % money)

# %f 는 값이 짧아도 소수점 아래 6자리를 0으로 채워서 보여 줘요
print("[%f]" % 1.5)
