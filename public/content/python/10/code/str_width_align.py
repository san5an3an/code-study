# 문자열의 자릿수 지정과 정렬 %10s, %-10s (강의 10강-형식문자를_활용한_문자열_포메팅.ipynb 문자열의 자리수 표현과 정렬 정리)

# 문자열의 자릿수 지정하기 -> 빈자리는 공백 지정만 가능해요
print("[%10s]에 살고 있습니다." % "대한민국")    # 오른쪽 정렬
print("[%-10s]에 살고 있습니다." % "대한민국")   # 왼쪽 정렬

# 슬라이드 예제
print("Hello %10s." % "Python")
print("Hello %-10s." % "Python")

# 문자열에 0을 붙여도 0으로 채워지지 않고 공백으로 채워져요
print("[%010s]" % "Python")
