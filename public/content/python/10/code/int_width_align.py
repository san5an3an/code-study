# 정수의 자릿수 지정과 정렬 %10d, %010d, %-10d (강의 10강-형식문자를_활용한_문자열_포메팅.ipynb 정수의 자리수 표현과 정렬 정리)
# 대괄호 [ ] 는 형식문자가 아니에요. 공백이 몇 칸인지 눈으로 보려고 같이 출력하는 글자예요

# 자릿수 지정하기 -> 오른쪽 정렬, 빈자리는 공백으로 채워요
print("[%10d]원을 입금했습니다." % 120000)

# 자릿수 지정하기 -> 오른쪽 정렬, 빈자리는 0으로 채워요
print("[%010d]원을 입금했습니다." % 120000)

# 자릿수 지정하기 -> 왼쪽 정렬, 빈자리는 공백으로 채워요 (0 채우기는 안 돼요)
print("[%-10d]원을 입금했습니다." % 120000)

# 왼쪽 정렬에 0을 같이 써 봐도 0은 무시되고 공백으로 채워져요
print("[%-010d]원을 입금했습니다." % 120000)

# 슬라이드 예제: 5자리로 맞추기
print("판매금액은 %5d원 입니다." % 350)
print("판매금액은 %-5d원 입니다." % 350)
print("판매금액은 %05d원 입니다." % 350)

# 지정한 자릿수보다 길면 자르지 않고 그냥 다 출력돼요
print("[%5d]" % 1234567)
