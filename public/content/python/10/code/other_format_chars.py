# 그 밖의 형식문자 %o, %x 와 % 자체 출력하기 %% (강의 슬라이드 문자열에 포함될 수 있는 형식문자 정리)

# %o 는 8진수, %x 는 16진수예요. 강사님 말대로 잘 쓰지는 않아요
print("8진수: %o" % 8)
print("16진수: %x" % 255)

# 형식문자는 % + 글자라서, % 기호 자체를 출력하려면 %% 처럼 두 개를 써요
print("할인율은 %d%% 입니다." % 30)

# % 연산자를 쓰지 않는 보통 문자열에서는 % 하나만 써도 그대로 나와요
print("할인율은 30% 입니다.")

# % 연산자를 쓰는데 % 를 하나만 쓰면 뒤 글자와 합쳐 형식문자로 읽혀서 에러가 나요(주석으로만 남김)
