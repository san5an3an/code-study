# 리스트를 원소로 갖는 딕셔너리 (강의 15강-딕셔너리.ipynb 리스트를 원소로 갖는 딕셔너리 정리)

# 바깥이 중괄호라서 전체는 딕셔너리예요. 값마다 리스트가 들어 있어요
student = {
    "name": ["철수", "민수", "호영", "수민"],
    "age": [16, 17, 19, 18],
    "height": [172.4, 168.2, 170.5, 165.8]
}
print(student)

# 민수는 각 리스트의 1번째(0부터 세요) 자리에 있어요
print(student["name"][1], student["age"][1], student["height"][1])
