# 기계어는 2진수, 어셈블리는 16진수: 숫자를 여러 진법으로 바꿔 보기 (강의 프로그래밍 언어의 발전 슬라이드 정리, 강의 밖 실습)

# 슬라이드의 기계어 예시 01000001 을 10진수로 바꿔요. int(글자, 2) 는 2진수로 읽으라는 뜻이에요
print(int("01000001", 2))

# 거꾸로 10진수 65 를 2진수로 바꿔요. 앞의 0b 는 "2진수예요"라는 표시예요
print(bin(65))

# 어셈블리 화면에 많이 나오는 16진수로도 바꿔요. 앞의 0x 는 "16진수예요"라는 표시예요
print(hex(65))

# 컴퓨터 안에서 65 는 영문자 A 를 나타내는 번호이기도 해요
print(chr(65))
