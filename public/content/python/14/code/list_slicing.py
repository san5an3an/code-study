# 리스트 슬라이싱: 구간을 잘라 새 리스트를 만듦 (강의 14강-리스트의_활용.ipynb 리스트의 슬라이싱 정리)

# 실습을 위한 샘플 데이터예요. 인덱스는 0~4, 뒤에서부터는 -1~-5예요
mylist = [60, 70, 80, 90, 100]

print(mylist[1:3])    # 1번째부터 3번째 전까지 (3번째는 포함 안 돼요)
print(mylist[:3])     # 처음부터 3번째 전까지
print(mylist[3:])     # 3번째부터 끝까지 (3번째도 포함돼요)
print(mylist[:])      # 모든 원소
print(mylist[1:-2])   # 1번째부터 -2번째 전까지 (-2번째인 90은 포함 안 돼요)

# 슬라이싱 결과는 새 리스트예요
part = mylist[1:3]
print(type(part))
