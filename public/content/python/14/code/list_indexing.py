# 리스트 인덱싱: 인덱스 번호로 원소 하나에 접근 (강의 14강-리스트의_활용.ipynb 리스트의 인덱싱 정리)

# 실습을 위한 샘플 데이터예요
mylist = [10, 20, 30, 40, 50]
print(mylist)

# 1번째 원소에 접근해요. 인덱스는 0부터 세요
print(mylist[1])

# -1번째 원소에 접근해요. 마이너스 인덱스는 뒤에서부터 -1, -2, ... 로 세요
print(mylist[-1])

# 인덱싱으로 원소 하나를 다른 변수에 복사하거나 값을 바꿀 수도 있어요 (강의 슬라이드 리스트의 인덱싱)
grade = [92, 83, 96]
eng = grade[1]
print(eng)
grade[2] = 88
print(grade)
