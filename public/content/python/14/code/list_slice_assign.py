# 슬라이싱 구간에 리스트를 대입해서 교체, 확장, 축소, 삭제하기 (강의 슬라이드 리스트의 슬라이싱 (1)~(4) 정리)

# 교체: 구간 길이(3개)와 같은 길이의 리스트를 넣으면 그 자리만 바뀌어요
data = [100, 200, 300, 400, 500]
data[1:4] = [2, 3, 4]
print(data)

# 확장: 구간보다 긴 리스트를 넣으면 뒤에 있던 원소가 뒤로 밀려나요
data = [100, 200, 300, 400, 500]
data[1:4] = [2, 3, 4, 5, 6, 7]
print(data)

# 축소: 구간보다 짧은 리스트를 넣으면 뒤에 있던 원소가 앞으로 당겨져요
data = [100, 200, 300, 400, 500]
data[1:4] = [2]
print(data)

# 삭제: 빈 리스트를 넣으면 그 구간이 통째로 지워져요
data = [100, 200, 300, 400, 500]
data[1:4] = []
print(data)
