# 출력값 정렬하기: > 오른쪽, < 왼쪽, ^ 가운데 (강의 슬라이드 "문자열 정렬 (1)"과 11강 ipynb "출력값 정렬하기" 정리)

# 슬라이드 예제: 콜론(:) 뒤에 정렬 기호와 전체 자릿수를 써요
print("이 {0:>10}(은)는 {1:>10}원 입니다.".format("사과", 1200))   # 10자리, 오른쪽 정렬
print("이 {0:<10}(은)는 {1:<10}원 입니다.".format("사과", 1200))   # 10자리, 왼쪽 정렬
print("이 {0:^10}(은)는 {1:^10}원 입니다.".format("사과", 1200))   # 10자리, 가운데 정렬

# 대괄호 [ ]로 감싸서 자릿수가 어디까지인지 눈으로 확인해요
# 5글자 오른쪽 정렬 -> "%5s"와 같아요
msg5 = "[{0:>5}]!!Python, [{1:>9}]~Python"
print(msg5.format("Hi", "Welcome"))

# 5글자 왼쪽 정렬 -> "%-5s"와 같아요
msg6 = "[{0:<5}]!!Python, [{1:<9}]~Python"
print(msg6.format("Hi", "Welcome"))

# 가운데 정렬
msg7 = "[{0:^10}]!!Python, [{1:^9}]~Python"
print(msg7.format("Hi", "Hello"))

# 정렬 기호를 안 쓰면 문자열은 왼쪽, 숫자는 오른쪽으로 정렬돼요
print("[{0:5}] [{1:5}]".format("ab", 12))
