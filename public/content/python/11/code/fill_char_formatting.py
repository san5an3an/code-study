# 공백을 특정 글자로 채우기 (강의 슬라이드 "문자열 정렬 (2)"와 11강 ipynb "공백을 특정 글자로 채우기" 정리)

# 슬라이드 예제: 정렬 기호 왼쪽에 빈칸을 채울 글자를 써요
print("이 {0:*>10}(은)는 {1:@>10}원 입니다.".format("사과", 1200))   # 오른쪽 정렬
print("이 {0:*<10}(은)는 {1:@<10}원 입니다.".format("사과", 1200))   # 왼쪽 정렬
print("이 {0:*^10}(은)는 {1:@^10}원 입니다.".format("사과", 1200))   # 가운데 정렬

# 실습 예제: 5글자 왼쪽 정렬 빈칸은 물결(~), 9글자 가운데 정렬 빈칸은 별표(*)
msg8 = "[{0:~<5}]!!Python!! [{1:*^9}]!!Python"
print(msg8.format("Hi", "Hello"))

# 채우는 글자로 0을 쓰면 값이 달라 보여도 그대로 출력해 줘요
print("{0:0<10}".format(1200))
