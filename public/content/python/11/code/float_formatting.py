# 소수점 표현하기: 소수점 자리수, 전체 자릿수, 0 채우기, 정렬 (강의 슬라이드 "문자열 정렬 (3)·(4)"와 11강 ipynb "소수점 표현하기" 정리)

# {0:f} 는 소수점 아래를 6자리로 맞춰 보여 줘요. {0} 처럼 형식을 안 쓰면 값 그대로 나와요
print("{0:f} + {1:0.3f}".format(123.456789, 12.34567))
print("{0:f} / {0}".format(12.34567))

# 소수점 4째자리까지 표현하기 -> 5째자리에서 반올림
msg9 = "{0:0.4f}"
print(msg9.format(123.456789))
print("{0:.4f}".format(123.456789))   # 앞의 0을 빼고 .4f 라고 써도 같아요

# 전체 10글자, 소수점 4째자리까지 표현하기 -> 빈자리는 공백, 오른쪽 정렬
msg10 = "[{0:10.4f}]"
print(msg10.format(123.456789))
print("[{0:10.4f}] + [{1:10.3f}]".format(123.456789, 12.34567))

# 전체 10글자, 공백은 0, 소수점 4째자리까지 표현하기
msg11 = "{0:010.4f}"
print(msg11.format(123.456789))
print("{0:010.4f} + {1:010.3f}".format(123.456789, 12.34567))

# 0을 채우면서 왼쪽 정렬, 가운데 정렬
print("{0:<010.4f} + {1:<010.3f}".format(123.456789, 12.34567))
print("{0:^010.4f} + {1:^010.3f}".format(123.456789, 12.34567))

# 0 대신 다른 글자로 채우려면 정렬 기호 앞에 그 글자를 써요
print("{0:$>10.2f} {0:!<10.2f}".format(3.14159))
