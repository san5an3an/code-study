# 인덱스 번호를 쓰는 치환 문자 {0}, {1} (강의 슬라이드 "치환문자를 활용한 문자열 포메팅 (1)"과 11강 ipynb "인덱스 번호를 사용한 포메팅" 정리)

# 슬라이드 예제: {0} 자리에 2000, {1} 자리에 "원"이 들어가요
# 강의에서는 변수 이름을 str 로 썼지만, str 은 파이썬이 이미 쓰는 이름이라 여기서는 text 로 바꿨어요
text = "이 과자는 {0}{1}입니다."
print(text.format(2000, "원"))

# 0번째 위치에 format() 함수에 전달된 0번째 값을 대입해요
msg1 = "I eat {0} apples"
print(msg1.format(3))

# 여러 개의 값을 혼용하기: 문자열이든 숫자든 자료형은 따지지 않고 순서만 맞으면 돼요
msg2 = "{0}은 {1}년 {2}월 {3}일 입니다."
print(msg2.format("개강일", 2023, 1, 26))

# 치환 문자는 문자열 안에서 순서를 바꿔 써도 되고, 같은 번호를 여러 번 써도 돼요
print("{1}, {0}, {1}".format("A", "B"))

