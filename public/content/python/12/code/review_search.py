# 프로젝트 문장 속 단어 찾기: find()로 "추천"이 들어 있는지 검사하기 (강의 프로젝트 슬라이드 문장속 단어 찾기 정리)

# 실제 과제는 review = input("리뷰를 입력하세요: ") 처럼 사용자에게 입력받아요
# 여기서는 매번 같은 결과가 나오도록 리뷰 문장을 직접 넣어 두었어요
review = "배송도 빠르고 품질이 좋아서 추천합니다"
p = review.find("추천")
print(p)   # 0 이상이면 "추천"이 들어 있는 거예요

review = "포장이 조금 아쉬웠어요"
p = review.find("추천")
print(p)   # -1 이면 "추천"이 없는 거예요

# 문장 맨 앞에 있으면 위치가 0 이에요. 그래서 "0보다 크다"가 아니라 "0 이상"으로 판단해요
review = "추천! 가격 대비 최고예요"
p = review.find("추천")
print(p)
