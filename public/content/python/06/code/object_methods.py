# 객체에 들어 있는 메서드 써 보기 (강의 06강-함수와_객체의_이해.ipynb 2. 객체의 이해 정리)
# 파이썬은 값을 만들면 그 값이 객체라서, 쓸 수 있는 함수(메서드)가 이미 들어 있어요

# 실수형 변수의 초기화
pi = 3.14

# 객체에 포함되는 메서드 활용하기 --> 소수점 올림
a = pi.__ceil__()
print(a)

# 객체에 포함되는 메서드 활용하기 --> 소수점 내림
b = pi.__floor__()
print(b)

# 객체.변수 (괄호 없음) : 객체 안에 들어 있는 값을 꺼내요
# 실수 객체에는 real(실수부)이라는 값이 들어 있어요
r = pi.real
print(r)

# 객체.함수() (괄호 있음) : 객체 안에 들어 있는 함수를 실행해요
# 실수 객체의 is_integer() 는 소수점 아래가 0인지 알려 줘요
print(pi.is_integer())
print((4.0).is_integer())

# 참고(강의 밖 내용): 앞뒤에 밑줄 두 개가 붙은 메서드는 보통 직접 부르지 않고
# math 모듈의 ceil(), floor() 를 써요. 결과는 같아요
import math
print(math.ceil(pi))
print(math.floor(pi))
