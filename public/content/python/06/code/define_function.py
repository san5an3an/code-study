# 함수 정의하고 사용하기 (강의 06강-함수와_객체의_이해.ipynb 1. 함수의 이해 정리)
# 수학의 f(x) = 2x + 1 을 파이썬 함수로 옮긴 거예요

# 함수 정의하기
# def 함수이름(파라미터): 다음 줄에 들여쓰기를 하고 명령어를 써요
# return 뒤에 적은 값(혹은 식의 결과)이 함수의 결과로 돌아가요
def f(x):
    return 2 * x + 1   # * 는 곱하기예요

# 함수 사용하기 (1): 2가 x로 들어가서 2 * 2 + 1 = 5 가 돌아와요
y = f(2)
print(y)

# 함수 사용하기 (2): 5가 x로 들어가서 2 * 5 + 1 = 11 이 돌아와요
z = f(5)
print(z)

# 강의 슬라이드 예: 1을 주면 2 * 1 + 1 = 3 이 돌아와요
print(f(1))

# 한 번 정의한 함수는 입력값만 바꿔서 몇 번이든 다시 써요(재사용)
print(f(3))

