# 정수와 실수 서로 바꾸기 (강의 06강-함수와_객체의_이해.ipynb 정수를 실수로, 실수를 정수로 변환 정리)

# 정수를 실수로 변환 --> 정수 뒤에 ".0"이 붙어요
num1 = 100
num2 = float(num1)
print(num2)

# 변환 결과의 데이터 타입 확인 --> 실수(float)
t1 = type(num2)
print(t1)

# 실수를 정수로 변환 --> 소수점을 버려요(반올림이 아니에요)
num3 = 123.78
num4 = int(num3)
print(num4)

# 변환 결과의 데이터 타입 확인 --> 정수(int)
t2 = type(num4)
print(t2)

# 참고: 음수도 소수점을 그냥 잘라 내서 0 쪽으로 가까워져요
print(int(-3.7))
