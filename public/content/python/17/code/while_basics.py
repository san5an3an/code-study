# while문의 기본 특성: 초기식, 조건식, 증감식 (강의 17강-반복문(1)-while.ipynb While문의 기본 특성 정리)

x = 1                      # 초기식 -> 조건을 판별할 기준값을 만들어요
while x <= 10:             # 조건식 -> x가 10보다 작거나 같은 동안 반복해요
    print("x=%d" % x)      # 반복이 진행되는 동안 수행할 명령이에요
    x += 1                 # 증감식 -> 조건에 쓰이는 값을 바꿔요

# 반복이 끝난 뒤 x는 조건이 처음으로 거짓이 된 값(11)이에요
print("x의 최종값 =", x)

