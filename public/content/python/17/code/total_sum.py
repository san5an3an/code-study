# 1~10까지의 총 합 구하기 (강의 17강-반복문(1)-while.ipynb 총 합 구하기 정리)

x = 1               # 초기식
sum = 0             # 총 합을 누적해서 저장할 변수예요. 반복 전에 꼭 0으로 시작해요
while x <= 10:      # 조건식 -> x가 10보다 작거나 같은 동안 반복해요
    sum += x        # sum이 스스로 x만큼 증가해요
    print("x=%d, sum=%d" % (x, sum))
    x += 1          # 증감식 -> 조건에 쓰이는 값을 바꿔요
