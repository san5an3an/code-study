# 리스트의 원소 탐색하기: 인덱스 0부터 len()보다 작은 동안 반복 (강의 17강-반복문(1)-while.ipynb 리스트의 원소 탐색하기 정리)

mylist = [10, 20, 30, 40, 50]   # 실습을 위한 리스트를 준비해요
size = len(mylist)              # 리스트의 전체 원소 수예요(5)
i = 0                           # 0부터 셀 리스트의 인덱스예요

# 인덱스가 전체 원소 수보다 작은 동안 반복해요. i는 0, 1, 2, 3, 4가 돼요
while i < size:
    x = mylist[i]               # i번째 원소를 꺼내요
    mylist[i] = x * 10          # 꺼낸 값에 10을 곱해서 다시 i번째 위치에 저장해요
    i += 1                      # 다음 원소를 탐색하려고 인덱스를 1 증가해요

print(mylist)
