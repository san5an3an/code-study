# 파이썬 버전 확인하기 (강의 슬라이드 "파이썬 설치 여부 확인하기" 정리)
# 명령 프롬프트에서 python --version 을 치는 것과 같은 정보를 코드 안에서 꺼내 봐요
import sys

# 큰 버전 번호예요. 지금 쓰는 파이썬은 모두 3이에요
print("큰 버전:", sys.version_info.major)

# 강의에서 설치한 3.11.1보다 새 버전인지 비교해 봐요. 튜플끼리 앞자리부터 차례로 비교돼요
print("3.11.1 이상인가요?", sys.version_info >= (3, 11, 1))

