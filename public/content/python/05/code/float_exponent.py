# 실수형 변수와 지수 표기법 (강의 05강-변수의_이해.ipynb 실수형, 지수형태 정리)

# 소수점이 있는 수는 실수(float)예요
c = 1.2
d = -3.45
print(c)
print(d)

# e5 는 "10의 5제곱을 곱한다"는 뜻이에요. 소수점이 오른쪽으로 5칸 이동해요
e = 3e5          # 3 * (10의 5제곱)
print(e)         # 300000.0

# e-5 는 "10의 -5제곱을 곱한다"는 뜻이에요. 소수점이 왼쪽으로 5칸 이동해요
f = 3e-5         # 3 * (10의 -5제곱)
print(f)         # 0.00003 인데, 너무 작아서 파이썬이 3e-05 로 보여줘요
print(f == 0.00003)  # 값은 똑같아서 True 가 나와요

# 강의에서 값을 바꿔서 다시 확인한 예예요
e = 4.24e5       # 4.24 * (10의 5제곱)
print(e)         # 424000.0
f = 4.24e-3      # 4.24 * (10의 -3제곱)
print(f)         # 0.00424
