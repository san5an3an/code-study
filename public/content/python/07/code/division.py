# 나눗셈 관련 연산자 /, //, % (강의 07강-연산자.ipynb 나눗셈 관련 연산자 정리)

# / 는 소수점 아래까지 계산해요. 끝자리는 컴퓨터가 담을 수 있는 자리에서 반올림돼요
print(10 / 3)
print(10 / 4)

# // 는 소수점 아래를 버리고 몫만 구해요
print(10 // 3)
print(10 // 4)

# % 는 나머지만 구해요
print(10 % 3)
print(10 % 4)

# / 는 나눠 떨어져도 결과가 실수예요
print(10 / 5)

# 0 으로는 나눌 수 없어요. 실행하면 멈추니까 주석으로만 남겨요
