# 비교 연산자: 결과는 True 나 False 로 나와요 (강의 07강-연산자.ipynb 비교 연산자 정리)

print(100 == 50)   # 같다
print(100 != 50)   # 다르다
print(100 >= 50)   # 크거나 같다(이상)
print(100 > 50)    # 크다(초과)
print(100 < 50)    # 작다(미만)
print(100 <= 50)   # 작거나 같다(이하)

# 비교 연산도 하나의 수식이라서 결과를 다른 변수에 담을 수 있어요
result = 100 > 50
print(result)
