# 기본적인 사칙 연산 (강의 07강-연산자.ipynb 기본적인 사칙 연산 정리)

# 연산 결과는 새로운 변수에 할당하거나 직접 출력할 수 있어요
a = 3
b = 4
c = a + b
print(c)

# 연산 결과를 print 안에서 바로 출력해요
print(a - b)
print(a * b)
print(a / b)

# 정수와 실수를 같이 계산하면 정수가 실수로 바뀌어서 결과도 실수가 돼요
print(1 + 1.2)

# 곱하기 기호를 두 번 쓰면 거듭제곱이에요. 2 ** 5 는 2 * 2 * 2 * 2 * 2 와 같아요
print(2 ** 5)
print(3 ** 5)
