# 단항 연산자(강의 이름): 연산 결과를 다시 자기 자신에게 대입하는 줄임 표현 (강의 07강-연산자.ipynb 단항 연산자 정리)

# x = x + 5 를 줄여서 x += 5 로 써요. "x 스스로 5 증가" 라고 읽으면 쉬워요
x = 100
x = x + 5
print(x)

x = 100
x += 5
print(x)

# 강의 예제: a 가 한 줄씩 계속 바뀌어요
a = 1
a += 100   # 1 + 100 -> 101
a *= 10    # 101 * 10 -> 1010
a //= 3    # 1010 // 3 -> 336
a %= 5     # 336 % 5 -> 1
print(a)
