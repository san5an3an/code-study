// 05강 예제 3: printf 로 정수/실수 서식 출력
// 기본 모양: System.out.printf("출력서식", 값1, 값2, ...);
public class FormatExample {
    public static void main(String[] args) {
        // %d 자리에 정수가 순서대로 들어간다 (서식 3개 -> 값 3개)
        System.out.printf("%d %d %d\n", 10, 20, 30);  // 10 20 30

        // 따옴표 안의 일반 글자는 그대로 나오고, %d 자리만 값으로 바뀐다
        System.out.printf("나이 : %d\n", 25);          // 나이 : 25

        // \n 을 여러 번 쓰면 빈 줄이 생기고, \t 는 탭(넓은 간격)을 넣는다
        System.out.printf("\n\n나\t이 : %d\n", 30);

        // %5d  : 5칸을 잡고 오른쪽에 붙여서 출력 (앞에 빈칸)
        // %-5d : 5칸을 잡고 왼쪽에 붙여서 출력 (뒤에 빈칸)
        // # 은 아무 의미 없는 표시 기호. 칸이 몇 개인지 눈으로 보려고 붙였다
        System.out.printf("나이 : #%5d#\n", 25);       // 나이 : #   25#
        System.out.printf("나이 : #%-5d#\n", 25);      // 나이 : #25   #

        // %f : 실수(소수점 있는 수). 기본은 소수점 아래 6자리
        System.out.printf("%f %f\n", 1.2, 3.4);        // 1.200000 3.400000
        System.out.printf("키:%f\n", 165.7);           // 키:165.700000

        // %9.2f  : 전체 9칸, 소수점 아래 2자리, 오른쪽 정렬
        // %-9.2f : 전체 9칸, 소수점 아래 2자리, 왼쪽 정렬
        // %.2f   : 전체 칸은 신경 안 쓰고 소수점 아래 2자리만
        System.out.printf("키:#%9.2f#\n", 165.7);      // 키:#   165.70#
        System.out.printf("키:#%-9.2f#\n", 165.7);     // 키:#165.70   #
        System.out.printf("키:#%.2f#\n", 165.7);       // 키:#165.70#
    }
}
